function buildDeck() {
  const deck = MAJOR_ARCANA.map(([n, ko, en, up, rev, upText, revText]) => ({
    id: `major-${n}`,
    arcana: "major",
    suit: null,
    numeral: ROMAN[n],
    nameKo: ko,
    nameEn: en,
    upright: up,
    reversed: rev,
    uprightText: upText,
    reversedText: revText,
  }));

  for (const [suitKey, suit] of Object.entries(SUITS)) {
    RANKS.forEach(([rankKey, rankKo, rankEn, mark], i) => {
      const [up, rev] = MINOR_KEYWORDS[suitKey][i];
      const firstUp = up.split(", ")[0];
      const firstRev = rev.split(", ")[0];
      deck.push({
        id: `${suitKey}-${rankKey}`,
        arcana: "minor",
        suit: suitKey,
        numeral: mark,
        nameKo: `${suit.ko} ${rankKo}`,
        nameEn: `${rankEn} of ${suit.en}`,
        upright: up,
        reversed: rev,
        uprightText: `${suit.area} 면에서 '${firstUp}'의 기운이 강하게 작용합니다.`,
        reversedText: `${suit.area} 면에서 흐름이 뒤집혀 '${firstRev}' 쪽으로 기울어 있습니다.`,
      });
    });
  }
  return deck;
}

